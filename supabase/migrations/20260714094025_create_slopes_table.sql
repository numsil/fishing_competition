-- 슬로프(낚시터/진수 지점) 테이블
-- 기존 정적 에셋(assets/data/slopes.json)을 DB로 이전.
-- 전체 읽기 공개, 쓰기(추가/수정/삭제)는 관리자(users.role='admin')만.

-- 1) 테이블 ─────────────────────────────────────────────
CREATE TABLE public.slopes (
  id          text PRIMARY KEY,                 -- 기존 ID 유지 (s001 …)
  name        text NOT NULL,
  address     text NOT NULL,
  sido        text NOT NULL,                    -- 시/도 (지역 카테고리)
  sigungu     text NOT NULL DEFAULT '',         -- 시/군/구
  water_body  text NOT NULL DEFAULT '',         -- 수계
  lat         double precision,
  lng         double precision,
  thumb_url   text,                             -- 위성 썸네일 URL (없으면 앱이 내장 에셋 폴백)
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);

-- 목록 조회 정렬용 (시도 → 시군구 → 이름)
CREATE INDEX slopes_region_idx
  ON public.slopes (sido, sigungu, name);

-- updated_at 자동 갱신 트리거
CREATE OR REPLACE FUNCTION public.tg_slopes_updated_at()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END $$;

CREATE TRIGGER slopes_updated_at
  BEFORE UPDATE ON public.slopes
  FOR EACH ROW EXECUTE FUNCTION public.tg_slopes_updated_at();

-- 2) RLS ────────────────────────────────────────────────
ALTER TABLE public.slopes ENABLE ROW LEVEL SECURITY;

-- 읽기: 누구나 (비로그인 포함)
CREATE POLICY "Slopes are viewable by everyone."
  ON public.slopes FOR SELECT
  USING (true);

-- 쓰기(INSERT/UPDATE/DELETE): 관리자만
CREATE POLICY "Admins can insert slopes."
  ON public.slopes FOR INSERT
  WITH CHECK (EXISTS (
    SELECT 1 FROM public.users u
    WHERE u.id = auth.uid() AND u.role = 'admin'
  ));

CREATE POLICY "Admins can update slopes."
  ON public.slopes FOR UPDATE
  USING (EXISTS (
    SELECT 1 FROM public.users u
    WHERE u.id = auth.uid() AND u.role = 'admin'
  ))
  WITH CHECK (EXISTS (
    SELECT 1 FROM public.users u
    WHERE u.id = auth.uid() AND u.role = 'admin'
  ));

CREATE POLICY "Admins can delete slopes."
  ON public.slopes FOR DELETE
  USING (EXISTS (
    SELECT 1 FROM public.users u
    WHERE u.id = auth.uid() AND u.role = 'admin'
  ));

