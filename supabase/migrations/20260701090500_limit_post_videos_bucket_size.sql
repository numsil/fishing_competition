-- [비용] post_videos 버킷 업로드 용량 상한 50MB (압축본 기준, 서버 강제)
--
-- 앱은 업로드 전 영상을 720p로 압축하지만 버킷에 상한이 없어(제한없음) 긴 영상은 여전히 커질 수 있고,
-- 앱을 우회한 원본 업로드도 막지 못했음. 서버 측 상한으로 실제 저장/전송 비용을 캡.
-- 50MB = 720p 약 2~3분. 기존 파일에는 영향 없고 신규 업로드에만 적용.

UPDATE storage.buckets
SET file_size_limit = 52428800   -- 50 * 1024 * 1024
WHERE id = 'post_videos';
